async function main() {
  let created = 0;
  for (const h of HERBS) {
    if (h.cat === "skip") continue;
    const exists = await prisma.herb.findFirst({ where: { pinyinName: h.p } });
    if (exists) continue;
    await prisma.herb.create({
      data: {
        pinyinName: h.p, chineseName: h.c, latinName: h.lat, englishName: h.eng,
        category: h.cat, nature: h.nat, flavor: h.flav, meridianTropism: h.merid,
        dosageRange: h.dose, description: h.desc, modernPharmacology: h.pharm,
        status: "PUBLISHED",
      },
    });
    created++;
  }
  console.log(`Added ${created} new herbs.`);
  console.log(`Total herbs in DB: ${await prisma.herb.count()}`);
  await prisma.$disconnect();
}
main().catch(async (e) => { console.error(e); await prisma.$disconnect(); process.exit(1); });
