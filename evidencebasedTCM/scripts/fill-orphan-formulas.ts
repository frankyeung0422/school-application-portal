async function resolveHerbId(name: string, cache: Map<string, string | null>): Promise<string | null> {
  if (cache.has(name)) return cache.get(name)!;
  const candidates = herbAliases[name] ?? [name];
  for (const candidate of candidates) {
    // exact pinyin match (canonical form, no "(note)" suffix)
    let h = await prisma.herb.findFirst({ where: { pinyinName: candidate } });
    if (h) { cache.set(name, h.id); return h.id; }
    // try pinyin match ignoring suffixes (e.g., "Bai Zhu (note)")
    h = await prisma.herb.findFirst({ where: { pinyinName: { startsWith: candidate + " " } } });
    if (h) { cache.set(name, h.id); return h.id; }
  }
  cache.set(name, null);
  return null;
}

async function main() {
  // Process ALL formulas that have a composition entry — idempotent re-runs
  // will pick up newly added herbs without duplicating existing links.
  const targetPinyins = Object.keys(compositions);
  const targets = await prisma.formula.findMany({
    where: { pinyinName: { in: targetPinyins } },
    select: { id: true, pinyinName: true, chineseName: true, herbs: { select: { herbId: true } } },
  });
  console.log(`\nProcessing ${targets.length} formulas with known compositions.`);
  console.log(`Have composition entries for ${targetPinyins.length} formulas.`);

  const herbCache = new Map<string, string | null>();
  let formulasTouched = 0;
  let totalLinks = 0;
  const missingHerbs = new Map<string, number>();
  const skippedFormulas: string[] = [];

  for (const f of targets) {
    const comp = compositions[f.pinyinName];
    if (!comp) { skippedFormulas.push(f.pinyinName); continue; }
    const existingHerbIds = new Set(f.herbs.map((h) => h.herbId));
    let linksAdded = 0;
    for (const fh of comp) {
      const herbId = await resolveHerbId(fh.pinyin, herbCache);
      if (!herbId) {
        missingHerbs.set(fh.pinyin, (missingHerbs.get(fh.pinyin) ?? 0) + 1);
        continue;
      }
      if (existingHerbIds.has(herbId)) continue;
      try {
        await prisma.formulaHerb.create({
          data: { formulaId: f.id, herbId, role: fh.role, dosage: fh.dose ?? null },
        });
        existingHerbIds.add(herbId);
        linksAdded++;
        totalLinks++;
      } catch {
        // Duplicate composite key — already linked. Ignore.
      }
    }
    if (linksAdded > 0) formulasTouched++;
  }

  console.log(`\n[result] Updated ${formulasTouched} formulas with ${totalLinks} new herb links.`);
  if (skippedFormulas.length > 0) {
    console.log(`\n[skipped] ${skippedFormulas.length} formulas (no composition entry):`);
    for (const p of skippedFormulas.slice(0, 20)) console.log(`  - ${p}`);
    if (skippedFormulas.length > 20) console.log(`  ... and ${skippedFormulas.length - 20} more`);
  }
  if (missingHerbs.size > 0) {
    console.log(`\n[missing herbs] ${missingHerbs.size} herb names not found in DB (totals: ${Array.from(missingHerbs.values()).reduce((a, b) => a + b, 0)} skipped links):`);
    const sorted = Array.from(missingHerbs.entries()).sort((a, b) => b[1] - a[1]);
    for (const [name, count] of sorted.slice(0, 30)) console.log(`  - ${name} (×${count})`);
  }

  const stillEmpty = await prisma.formula.count({ where: { herbs: { none: {} } } });
  console.log(`\n[after] formulas still without herbs: ${stillEmpty}`);

  await prisma.$disconnect();
}

main().catch(async (e) => { console.error(e); await prisma.$disconnect(); process.exit(1); });
