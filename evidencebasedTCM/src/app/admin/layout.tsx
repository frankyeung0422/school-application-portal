export default async function AdminLayout({ children }: { children: React.ReactNode }) {
  const session = await auth();

  if (!session?.user) redirect("/login?callbackUrl=/admin");

  const userRole = (session.user as { role?: string }).role;
  if (userRole !== "ADMIN" && userRole !== "EDITOR") {
    redirect("/?error=unauthorized");
  }

  const locale = await getLocale();
  const messages = getMessages(locale);

  return (
    <div className="flex min-h-[calc(100vh-4rem)]">
      <aside className="w-64 shrink-0 border-r border-border bg-surface">
        <div className="p-4 border-b border-border">
          <h2 className="font-bold text-primary text-lg">{t(messages, "admin.panelTitle")}</h2>
          <p className="text-xs text-muted mt-0.5">
            {session.user.name || session.user.email} ({userRole})
          </p>
        </div>
        <nav className="p-2 space-y-0.5">
          {adminLinks.map((link) => (
            <Link
              key={link.href}
              href={link.href}
              className="flex items-center gap-2.5 rounded-lg px-3 py-2 text-sm text-muted hover:text-foreground hover:bg-background transition-colors"
            >
              <svg className="h-4 w-4 shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d={link.icon} />
              </svg>
              {t(messages, link.labelKey)}
            </Link>
          ))}
        </nav>
      </aside>

      <div className="flex-1 p-6 bg-background">{children}</div>
    </div>
  );
}
